"""三个导出目标。

总原则：**别人的格式一律是导出目标，不是执行路径。** `xirang` 内部只有一条路
走到底，这些只是同一份解析模型的投影。

  core     fusesoc CAPI2。加的段必须是**上游会忽略而不是报错**的，否则
           「产出可被原版 fusesoc 消费」那条铁律就断了
  kconfig  嵌套菜单。装配的每一层都是一个 menu，子包的旋钮自动嵌进去
  tar      零工具依赖的包：生成好的源码 + 一个 Makefile
"""
